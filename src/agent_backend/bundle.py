"""Agent bundles: the unit of deployment the backend discovers and serves.

A bundle is a folder under ``AGENTS_DIR``::

    <slug>/
      graph.json      generated by the compiler   (required)
      assets.json     generated by the compiler
      knowledge.md    copied by the compiler from the agent definition
      agent.yaml      hand-written runtime settings (optional)
      tools/          hand-written tool plugin (optional)

Agents that need the same tools (e.g. a text and a voice variant) can instead
point ``agent.yaml: tools:`` at a shared plugin at ``<AGENTS_DIR>/_tools/<name>/``.

Updating an agent's flow means replacing the generated files; ``agent.yaml``
and ``tools/`` are never produced or overwritten by the compiler.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import yaml
from pydantic import BaseModel, ConfigDict, Field

from agent_backend.channels.ghl.client import DEFAULT_TOKEN_ENVS

GRAPH_FILE = "graph.json"
ASSETS_FILE = "assets.json"
KNOWLEDGE_FILE = "knowledge.md"
CONFIG_FILE = "agent.yaml"
TOOLS_DIR = "tools"
SHARED_TOOLS_DIR = "_tools"


class GhlChannelConfig(BaseModel):
    """GoHighLevel webhook settings for one agent.

    Phone gating variables default to ``<SLUG>_ALLOWED_PHONES`` and
    ``<SLUG>_ENFORCE_PHONE_WHITELIST`` (see ``AgentConfig.env_prefix``).

    Attributes:
        path: Route, relative to ``/agents/<slug>``, that receives the webhook.
        token_envs: Environment variables tried in order for the GHL token.
        debounce_seconds: Quiet time before buffered messages become one turn.
        allowed_phones_env: Variable holding the comma-separated allow-list.
        enforce_whitelist_env: Variable switching the allow-list on or off.
        default_allowed_phones: Allow-list used when the variable is unset.
        closing_message_lookback_days: Safety bound of the closing sweep.
        closing_message: Override text (or per-language texts) of the sweep.
        unsupported_media_message: Override reply for text-less messages.
        redirect_widget_to_whatsapp: Answer widget messages over WhatsApp.
    """

    model_config = ConfigDict(extra="forbid")

    path: str = "/ghl"
    token_envs: tuple[str, ...] = DEFAULT_TOKEN_ENVS
    debounce_seconds: float = 15.0
    allowed_phones_env: str | None = None
    enforce_whitelist_env: str | None = None
    default_allowed_phones: str = ""
    closing_message_lookback_days: float = 3.0
    closing_message: str | dict[str, str] | None = None
    unsupported_media_message: str | dict[str, str] | None = None
    redirect_widget_to_whatsapp: bool = True


class AgentConfig(BaseModel):
    """Contents of a bundle's optional ``agent.yaml``.

    Attributes:
        env_prefix: Prefix of the agent's environment variables. Defaults to
            the upper-cased slug.
        tool_route_suffixes: Route suffixes tried before a tool's plain name, in
            order. ``["-ghl"]`` makes a call to ``book_appointment`` hit
            ``book-appointment-ghl`` first and fall back to ``book-appointment``.
        tools: Name of a shared tool plugin under ``<AGENTS_DIR>/_tools/``. When
            unset, the bundle's own ``tools/`` folder is used, if present.
        ghl: GHL webhook settings; ``None`` disables that channel.
    """

    model_config = ConfigDict(extra="forbid")

    env_prefix: str | None = None
    tool_route_suffixes: tuple[str, ...] = ()
    tools: str | None = Field(default=None, pattern=r"^[A-Za-z0-9_\-]+$")
    ghl: GhlChannelConfig | None = Field(default=None)


@dataclass(frozen=True)
class AgentBundle:
    """One discovered agent bundle.

    Attributes:
        slug: Folder name; also the URL segment and the checkpoint namespace.
        root: Absolute path of the bundle folder.
        config: Parsed ``agent.yaml`` (defaults when the file is absent).
    """

    slug: str
    root: Path
    config: AgentConfig

    @property
    def graph_path(self) -> Path:
        """Path of the compiled graph.

        Returns:
            ``<root>/graph.json``.
        """
        return self.root / GRAPH_FILE

    @property
    def knowledge_path(self) -> Path:
        """Path of the optional knowledge document.

        Returns:
            ``<root>/knowledge.md`` (may not exist).
        """
        return self.root / KNOWLEDGE_FILE

    @property
    def tools_dir(self) -> Path:
        """Folder of the agent's tool plugin.

        Returns:
            ``<AGENTS_DIR>/_tools/<name>`` when ``agent.yaml`` names a shared
            plugin, otherwise ``<root>/tools``. May not exist.
        """
        if self.config.tools:
            return self.root.parent / SHARED_TOOLS_DIR / self.config.tools
        return self.root / TOOLS_DIR

    @property
    def env_prefix(self) -> str:
        """Prefix used to derive the agent's environment variable names.

        Returns:
            The configured prefix, or the upper-cased slug.
        """
        return self.config.env_prefix or self.slug.upper()


def load_bundle(root: Path) -> AgentBundle:
    """Reads one bundle folder.

    Args:
        root: Folder containing ``graph.json``.

    Returns:
        The bundle, with default settings when ``agent.yaml`` is missing.

    Raises:
        FileNotFoundError: If ``graph.json`` is missing.
        ValueError: If ``agent.yaml`` is not valid for ``AgentConfig``.
    """
    if not (root / GRAPH_FILE).is_file():
        raise FileNotFoundError(f"No compiled agent at {root / GRAPH_FILE}; run the compiler's bundle command.")
    config_path = root / CONFIG_FILE
    raw = yaml.safe_load(config_path.read_text(encoding="utf-8")) if config_path.is_file() else None
    try:
        config = AgentConfig.model_validate(raw or {})
    except ValueError as exc:
        raise ValueError(f"Invalid {config_path}: {exc}") from exc
    return AgentBundle(slug=root.name, root=root.resolve(), config=config)


def discover_bundles(agents_dir: Path) -> dict[str, AgentBundle]:
    """Finds every bundle directly under ``agents_dir``.

    Folders without a ``graph.json`` are ignored, so a half-copied bundle or
    unrelated folder never breaks startup.

    Args:
        agents_dir: Directory to scan.

    Returns:
        Bundles keyed by slug, sorted by slug. Empty if the directory is missing.
    """
    if not agents_dir.is_dir():
        return {}
    return {
        entry.name: load_bundle(entry)
        for entry in sorted(agents_dir.iterdir())
        if entry.is_dir() and (entry / GRAPH_FILE).is_file()
    }
